""" ------------------------ 不定长参数(位置参数、关键字参数) ------------------------ """


def f5(*args, **kwargs):
    print(args)  # (1, 2, 3)
    print(kwargs)  # {'a': 1, 'b': 2, 'c': 3}


# f5(1, 2, 3, a=1, b=2, c=3)


""" ------------------------ 匿名函数 ------------------------ """


def f6(*args, **kwargs):
    # 参数+返回值
    sum = lambda x, y: x + y
    print(sum(1, 2))  # 3
    # 参数+表达式
    test1 = lambda msg: print(f"---{msg}---")
    test1("hello world")  # ---hello world---
    # 无参数+表达式
    test2 = lambda: print(123)
    test2()  # 123


f6()
