""" ------------------------ 基础 ------------------------ """
def f1():
  n1 = 5
  match n1:
    case 1:
      print("n1 等于 1")
    case 2:
      print("n1 等于 2")
    # 支持使用 | 运算符进行多个值的匹配
    case 3 | 4:
      print("n1 等于 3 或 4")
    # 支持添加条件判断
    case 5 if n1 > 6:
      print("n1 等于 5")
    case _:
      print("n1 不等于 1 也不等于 2") 
f1()
