"""运算符
- if: 条件判断
- elif: 否则如果
- else: 否则
"""

""" ------------------------ 基础 ------------------------ """
def f1():
  n1 = 1
  n2 = 2
  if n1 > n2:
    print("n1 大于 n2")
  else:
    print("n1 不大于 n2")

  # 多个条件使用括号括起来
  n3 = 3
  if (n3 > n2):
    print("n3 大于 n2")
  else:
    print("n3 不大于 n2")
f1()
