"""数字
- 保留小数位
  - 格式: {变量:.保留小数位f} => f(float)
  - round(number, ndigits): 四舍五入
- 相关方法
  - int(x): 将x转换为整数
  - float(x): 将x转换为浮点数
"""

""" ------------------------ 精度问题 ------------------------ """
def f1():
    n1 = 0.5
    n2 = 0.4
    print(n1 - n2)  # 0.09999999999999998
# f1()

""" ------------------------ 保留小数位 ------------------------ """
def f2():
    n1 = 0.123456
    print(f"{n1:.1f}")  # 0.1
    print(f"{n1:.2f}")  # 0.12
f2()
